import { readdirSync, lstatSync, readFileSync, writeFileSync, renameSync, existsSync } from 'node:fs';
import { resolve, join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const cmp = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const posix = p => p.split(sep).join('/');
const groups = [['towers', 'getTower', 'towerFactories'], ['maps', 'getMap', 'mapFactories'], ['knowledge', 'getKnowledge', 'knowledgeFactories']];
function entries(base, path) {
  const dir = resolve(base, path);
  // Never follow links, including links in parent directories.
  let current = base;
  for (const part of relative(base, dir).split(sep)) {
    if (!part || part === '.' || part === '..') throw new Error(`Unsafe directory: ${path}`);
    current = join(current, part);
    if (!existsSync(current)) return [];
    const stat = lstatSync(current);
    if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error(`Unsafe directory: ${path}`);
  }
  return readdirSync(dir, { withFileTypes: true }).sort((a,b)=>cmp(a.name,b.name));
}
function inventory(base, path, out) {
  for (const entry of entries(base, path)) {
    const child = `${path}/${entry.name}`;
    if (entry.isSymbolicLink()) throw new Error(`Symlink forbidden: ${child}`);
    if (entry.isDirectory()) inventory(base, child, out);
    else if (entry.isFile() && /\.(svg|png|webp|jpg|jpeg|gif|avif)$/i.test(entry.name)) {
      const bytes = readFileSync(resolve(base, child));
      if (!bytes.length) throw new Error(`Empty resource: ${child}`);
      if (/\.svg$/i.test(entry.name) && !/<svg(?:\s|>)/i.test(bytes.toString('utf8'))) throw new Error(`Invalid SVG: ${child}`);
      out[child.slice('public/'.length)] = createHash('sha256').update(bytes).digest('hex');
    }
  }
}
export function generateSource(base = root) {
  const imports = [], exports = [];
  for (const [folder, method, registry] of groups) {
    const names = [];
    for (const entry of entries(base, `src/content/${folder}`)) {
      if (entry.isSymbolicLink()) throw new Error(`Symlink forbidden: ${folder}/${entry.name}`);
      if (!entry.isFile() || !entry.name.endsWith('.ts') || entry.name.endsWith('.d.ts')) continue;
      const name = entry.name.slice(0,-3);
      if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`Invalid module name: ${folder}/${entry.name}`);
      const alias = `${folder}_${names.length}`;
      imports.push(`import { ${method} as ${alias} } from './${folder}/${name}';`);
      names.push(alias);
    }
    exports.push(`export const ${registry} = [${names.join(', ')}] as const;`);
  }
  const assets = Object.create(null);
  inventory(base, 'public/art', assets);
  const sorted = Object.fromEntries(Object.entries(assets).sort(([a],[b])=>cmp(a,b)));
  return ['// Generated by scripts/generate-content.mjs. Do not edit.', ...imports, '', ...exports, `export const resourceHashes: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 2)};`, ''].join('\n');
}
export function generate(base = root, check = false) {
  const file = resolve(base, 'src/content/generated.ts');
  const source = generateSource(base);
  if (existsSync(file) && lstatSync(file).isSymbolicLink()) throw new Error('Unsafe generated.ts');
  if (existsSync(file) && readFileSync(file,'utf8') === source) return false;
  if (check) throw new Error('Stale content registry; run node scripts/generate-content.mjs');
  const temp = `${file}.${process.pid}.tmp`;
  writeFileSync(temp, source, { flag:'wx' });
  renameSync(temp,file);
  return true;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some(a=>a !== '--check')) throw new Error('Usage: node scripts/generate-content.mjs [--check]');
    console.log(generate(root,process.argv.includes('--check')) ? 'Content registry generated' : 'Content registry current');
  } catch(error) { console.error(error.message); process.exitCode = 1; }
}
